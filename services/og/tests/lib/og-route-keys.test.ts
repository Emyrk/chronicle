import { describe, expect, test } from 'vitest';
import { deriveLegacyRouteKey, resolveOgRouteKeys } from '../../app/lib/og-route-keys';

describe('resolveOgRouteKeys', () => {
  test('always serves the public og key', () => {
    expect([...resolveOgRouteKeys({})]).toEqual(['og']);
  });

  test('adds OG_API_PATH as an alias with slashes trimmed', () => {
    expect(resolveOgRouteKeys({ OG_API_PATH: '/custom_key/' }).has('custom_key')).toBe(true);
  });

  test('ignores OG_API_PATH values that are not a single safe segment', () => {
    expect([...resolveOgRouteKeys({ OG_API_PATH: 'a/b' })]).toEqual(['og']);
    expect([...resolveOgRouteKeys({ OG_API_PATH: '../etc' })]).toEqual(['og']);
  });

  test('keeps the path older versions derived from OG_SECRET', () => {
    const keys = resolveOgRouteKeys({ OG_SECRET: '  abc123  ' });
    expect(keys.has('og')).toBe(true);
    expect(keys.has(deriveLegacyRouteKey('abc123'))).toBe(true);
  });
});

describe('deriveLegacyRouteKey', () => {
  test('matches keys generated by the previous signing implementation', () => {
    // Values produced by the removed og-security module; published URLs depend on them.
    expect(deriveLegacyRouteKey('abc123')).toBe('og_fqc4xxjzrnmx');
    expect(deriveLegacyRouteKey('my-secret')).toBe('og_1eri06i10bv1');
  });
});
