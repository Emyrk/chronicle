type fileGroup struct {
	Filename  string
	Expansion string
	Type      string // "dungeon" or "raid"
}

var outputFiles = []fileGroup{
	{"gen_dungeons_vanilla.go", "vanilla", "dungeon"},
	{"gen_raids_vanilla.go", "vanilla", "raid"},
	{"gen_dungeons_tbc.go", "tbc", "dungeon"},
	{"gen_raids_tbc.go", "tbc", "raid"},
	{"gen_dungeons_wotlk.go", "wotlk", "dungeon"},
	{"gen_raids_wotlk.go", "wotlk", "raid"},
}

type genInstance struct {
	VarPrefix string
	Name      string
	ZoneNames []string
	MapID     uint32
	Bosses    []genEntry
	Adds      []genEntry
}

type genEntry struct {
	Entry uint32
	Name  string
}

func generateAllFiles(outputDir string, data map[uint32]*InstanceCreatures) error {
	for _, fg := range outputFiles {
		instances := collectInstances(fg.Expansion, fg.Type, data)
		if len(instances) == 0 {
			log.Printf("  Skipping %s (no data)", fg.Filename)
			continue
		}
		path := filepath.Join(outputDir, fg.Filename)
		if err := writeGoFile(path, instances); err != nil {
			return fmt.Errorf("write %s: %w", fg.Filename, err)
		}
		total := 0
		for _, inst := range instances {
			total += len(inst.Bosses) + len(inst.Adds)
		}
		log.Printf("  Wrote %s (%d instances, %d creatures)", fg.Filename, len(instances), total)
	}
	return nil
}

func collectInstances(expansion, typ string, data map[uint32]*InstanceCreatures) []genInstance {
	var result []genInstance
	for _, inst := range AllInstances {
		if inst.Expansion != expansion || inst.Type != typ {
			continue
		}
		creatures := data[inst.MapID]
		if creatures == nil {
			continue
		}
		result = append(result, genInstance{
			VarPrefix: inst.VarPrefix,
			Name:      inst.Name,
			ZoneNames: inst.ZoneNames,
			MapID:     inst.MapID,
			Bosses:    sortedEntries(creatures.Bosses),
			Adds:      sortedEntries(creatures.Adds),
		})
	}
	sort.Slice(result, func(i, j int) bool {
		return result[i].MapID < result[j].MapID
	})
	return result
}

func sortedEntries(m map[uint32]string) []genEntry {
	out := make([]genEntry, 0, len(m))
	for k, v := range m {
		out = append(out, genEntry{Entry: k, Name: v})
	}
	sort.Slice(out, func(i, j int) bool {
		return out[i].Entry < out[j].Entry
	})
	return out
}

// writeGoFile generates a single .go file containing hostiles functions
// and factory variables for the given instances.
func writeGoFile(path string, instances []genInstance) error {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "// Code generated by scripts/hostilegen; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: https://github.com/azerothcore/database-wotlk/\n\n")
	fmt.Fprintf(&buf, "package instances\n\n")
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\t\"github.com/Emyrk/chronicle/combatlog/parser/common/instances\"\n")
	fmt.Fprintf(&buf, ")\n")

	for _, inst := range instances {
		fmt.Fprintf(&buf, "\n// %sHostiles returns creature entry IDs for %s (map %d).\n",
			inst.VarPrefix, inst.Name, inst.MapID)
		fmt.Fprintf(&buf, "func %sHostiles() map[uint32]instances.Identity {\n", inst.VarPrefix)
		fmt.Fprintf(&buf, "\thostile := make(map[uint32]instances.Identity)\n")

		if len(inst.Adds) > 0 {
			fmt.Fprintf(&buf, "\tinstances.LoadAdds(hostile, map[uint32]string{\n")
			for _, e := range inst.Adds {
				fmt.Fprintf(&buf, "\t\t%d: %q,\n", e.Entry, e.Name)
			}
			fmt.Fprintf(&buf, "\t})\n")
		}

		if len(inst.Bosses) > 0 {
			fmt.Fprintf(&buf, "\tinstances.LoadBosses(hostile, map[uint32]string{\n")
			for _, e := range inst.Bosses {
				fmt.Fprintf(&buf, "\t\t%d: %q,\n", e.Entry, e.Name)
			}
			fmt.Fprintf(&buf, "\t})\n")
		}

		fmt.Fprintf(&buf, "\treturn hostile\n")
		fmt.Fprintf(&buf, "}\n")

		fmt.Fprintf(&buf, "\nvar %sFactory = &instances.CommonFactory{\n", inst.VarPrefix)
		fmt.Fprintf(&buf, "\tName:      %q,\n", inst.Name)
		fmt.Fprintf(&buf, "\tZoneNames: []string{")
		for i, zn := range inst.ZoneNames {
			if i > 0 {
				fmt.Fprintf(&buf, ", ")
			}
			fmt.Fprintf(&buf, "%q", zn)
		}
		fmt.Fprintf(&buf, "},\n")
		fmt.Fprintf(&buf, "\tMapIDs:    []uint32{%d},\n", inst.MapID)
		fmt.Fprintf(&buf, "\tHostiles:  instances.FromMap(%sHostiles()),\n", inst.VarPrefix)
		fmt.Fprintf(&buf, "}\n")
	}

	// Run gofmt on the output.
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Printf("warning: gofmt failed for %s, writing unformatted: %v", path, err)
		return os.WriteFile(path, buf.Bytes(), 0o644)
	}
	return os.WriteFile(path, formatted, 0o644)
}

var hostilesRe = regexp.MustCompile(`func (\w+)Hostiles\(\)`)

// scanExistingHostiles reads all non-generated .go files in dir and returns
// the set of VarPrefix values that already have a XxxHostiles() function.
func scanExistingHostiles(dir string) map[string]bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	found := make(map[string]bool)
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || filepath.Ext(name) != ".go" {
			continue
		}
		// Skip files we ourselves generate so a re-run doesn't skip everything.
		if len(name) > 4 && name[:4] == "gen_" {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			continue
		}
		for _, m := range hostilesRe.FindAllSubmatch(data, -1) {
			found[string(m[1])] = true
		}
	}
	return found
}

// metaMapIDByPrefix returns the map ID for a given VarPrefix, or 0 if unknown.
func metaMapIDByPrefix(prefix string) uint32 {
	for _, inst := range AllInstances {
		if inst.VarPrefix == prefix {
			return inst.MapID
		}
	}
	return 0
}
